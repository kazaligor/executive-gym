    public static List<Question> daily(ProgressStore store, int count){
        List<Question> copy=new ArrayList<>(ALL);
        Collections.shuffle(copy,new Random(System.currentTimeMillis()));
        Collections.sort(copy,(a,b)->{
            int sa=store.score(a.skill), sb=store.score(b.skill);
            return Integer.compare(sa,sb);
        });
        List<Question> out=new ArrayList<>();
        Set<String> skills=new HashSet<>();
        for(Question q:copy) if(out.size()<count){
            if(skills.size()<6 || !skills.contains(q.skill)){out.add(q);skills.add(q.skill);}
        }
        for(Question q:copy) if(out.size()<count && !out.contains(q)) out.add(q);
        Collections.shuffle(out,new Random(System.nanoTime()));
        return out;
    }


