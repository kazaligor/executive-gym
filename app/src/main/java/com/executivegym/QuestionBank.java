    private static void add(String s,String t,String sc,String[] o,int c,String e,String er,int d){
        ALL.add(new Question(s,t,sc,o,c,e,er,d));
    }

    public static List<Question> daily(ProgressStore store, int count){
        List<Question> copy=new ArrayList<>(ALL);
        Collections.shuffle(copy,new Random(System.currentTimeMillis()));
        Collections.sort(copy,(a,b)->{
            int sa=store.score(a.skill), sb=store.score(b.skill);
            return Integer.compare(sa,sb);
        });
        List<Question> out=new ArrayList<>();
        Set<String> skills=new HashSet<>();
        for(Question q:copy) if(out.size()<count){
            if(skills.size()<6 || !skills.contains(q.skill)){out.add(q);skills.add(q.skill);}
        }
        for(Question q:copy) if(out.size()<count && !out.contains(q)) out.add(q);
        Collections.shuffle(out,new Random(System.nanoTime()));
        return out;
    }


    public static List<String> skills(){
        return Arrays.asList("Стратегическое мышление","Решение и judgment","Лидерство и люди","Бизнес и P&L","Коммуникация руководителя","Личная эффективность");
    }

    public static List<Question> forSkill(ProgressStore store, String skill, int count){
        List<Question> pool=new ArrayList<>();
        for(Question q:ALL) if(q.skill.equals(skill)) pool.add(q);
        Collections.shuffle(pool,new Random(System.nanoTime()));
        Collections.sort(pool,(a,b)->Integer.compare(a.difficulty,b.difficulty));
        if(pool.size()>count) return new ArrayList<>(pool.subList(0,count));
        return pool;
    }

